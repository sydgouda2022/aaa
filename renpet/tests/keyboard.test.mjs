import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {COPTIC_LETTERS,COP_NUMBERS,EGY_NUMBERS,wordRange,suggestions,deleteGrapheme} from '../web/keyboard-core.js';

const read=async name=>JSON.parse(await readFile(new URL('../web/assets/dictionaries/'+name,import.meta.url),'utf8'));
const coptic=await read('coptic.json'),signs=await read('signs.json');
assert.equal(COPTIC_LETTERS.length,32,'Coptic alphabet occupies one page');
assert.equal(new Set(COPTIC_LETTERS).size,32,'Coptic keys are not duplicated');
assert.equal(COP_NUMBERS.length,12,'Coptic numbers stay on its single page');
assert.equal(EGY_NUMBERS.length,15,'Nine units and all six powers on every hieroglyphic page');
assert.ok(coptic.rows.length>=10000,'Two real Coptic lexica compiled offline');
assert.ok(coptic.rows.some(x=>x[1]===1),'Sahidic-only written forms present');
assert.ok(coptic.rows.some(x=>x[1]===2),'Bohairic-only written forms present');
assert.ok(coptic.rows.some(x=>x[1]===3),'Shared dialect forms merged');
assert.ok(signs.pages.uni.length>=20&&signs.pages.bi.length>=70&&signs.pages.tri.length>=45,'MDWNFR-style sign pages have viable Unicode inventories');
assert.ok(signs.pages.uni.every(x=>x[0]&&x[1]),'Sign catalog must retain Gardiner references');
const prefix='ⲡ';
const choices=suggestions(prefix,'cop',coptic,{},4);
assert.equal(choices[0].text,prefix,'Raw Coptic input always first');
assert.ok(choices.slice(1).some(x=>x.dialects&1),'Suggest Sahidic words');
assert.ok(choices.slice(1).some(x=>x.dialects&2),'Suggest Bohairic words');
const learned=suggestions('𓄿','egy',{rows:[]},{'egy:𓄿𓂝':9},4);
assert.equal(learned[0].text,'𓄿','Raw hieroglyphic signs first');
assert.equal(learned[1].text,'𓄿𓂝','Device-local learned hieroglyphic completions');
const cp=wordRange('ⲁⲡⲉ ⲥⲙ',7,'cop');
assert.equal(cp.raw,'ⲥⲙ','Coptic prefix finds the current word');
assert.equal(wordRange('𓄿𓅓 𓈖𓏏',9,'egy').raw,'𓈖𓏏','Hieroglyphic prefix follows sign clusters');
assert.equal(deleteGrapheme('𓄿𓂝',4,4).start,2,'Delete whole Unicode hieroglyph, not half surrogate');
assert.equal(deleteGrapheme('ⲁ̅',2,2).start,0,'Delete combining overline with its Coptic base');
const late=JSON.parse(await readFile(new URL('../web/lexicon/lexicon.json',import.meta.url),'utf8'));
const release=JSON.parse(await readFile(new URL('../web/lexicon/manifest.json',import.meta.url),'utf8'));
assert.equal(release.stage,'Late Egyptian','Dictionary is only Late Egyptian');
assert.equal(late.format,'mdwnfr-predict-v1','Same verified lexicon format as MdwNfr');
assert.equal(late.entries.length,release.spelling_records);
assert.equal(late.metadata.complete,false,'Current development seed is never declared full');
const lateRows={rows:late.entries.map(r=>[r.signs,r.attestations||1,r.lemma||r.ref])};
const example=late.entries.find(r=>r.signs.length>2);
assert.ok(example,'Native hieroglyphic spellings present');
const returned=suggestions([...example.signs][0],'egy',lateRows,{},4);
assert.equal(returned[0].text,[...example.signs][0],'Raw hieroglyphic input remains first');
assert.ok(returned.length>1&&returned.slice(1).every(v=>v.source==='LATE'),'No Earlier Egyptian suggestions');
const pop=await read('coptic-popular.json');
assert.ok(pop.rows.length>=750,'Coptic high-frequency supplemental corpus was packaged');
const augmented={rows:[...coptic.rows],popularity:Object.fromEntries(pop.rows)};
const existing=new Set(augmented.rows.map(x=>x[0]));
for(const [form] of pop.rows)if(!existing.has(form)){augmented.rows.push([form,0]);existing.add(form);}
const copticCommon=suggestions('ⲛ','cop',augmented,{},4);
assert.equal(copticCommon[0].text,'ⲛ');
assert.ok(copticCommon.length>=3,'Normalized frequency-backed Coptic completion works');
console.log('Renpet keyboard catalog and bilingual prediction tests passed');
